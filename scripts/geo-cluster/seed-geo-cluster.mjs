/** Абзац. Поддерживает **жирный** и [текст](/href). */
function p(text, style = "normal") {
  const children = [];
  const markDefs = [];
  const re = /(\*\*[^*]+\*\*)|(\[[^\]]+\]\([^)]+\))/g;
  let last = 0;
  let m;
  while ((m = re.exec(text))) {
    if (m.index > last) {
      children.push({ _key: key(), _type: "span", text: text.slice(last, m.index), marks: [] });
    }
    if (m[1]) {
      children.push({ _key: key(), _type: "span", text: m[1].slice(2, -2), marks: ["strong"] });
    } else {
      const label = m[2].slice(1, m[2].indexOf("]"));
      const href = m[2].slice(m[2].indexOf("(") + 1, -1);
      const dk = key();
      markDefs.push({ _key: dk, _type: "link", href });
      children.push({ _key: key(), _type: "span", text: label, marks: [dk] });
    }
    last = m.index + m[0].length;
  }
  if (last < text.length) {
    children.push({ _key: key(), _type: "span", text: text.slice(last), marks: [] });
  }
  return { _key: key(), _type: "block", style, markDefs, children };
}

