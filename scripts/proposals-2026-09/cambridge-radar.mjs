/* ── Запуск ───────────────────────────────────────────────────────────── */

const here = dirname(fileURLToPath(import.meta.url));
const backupDir = join(here, "..", "..", "backups", "proposals-2026-09");

async function main() {
  if (DOC_ID.includes(".")) {
    throw new Error("_id з крапкою не читається без токена — див. CLAUDE.md, «Dot rule»");
  }

  let folds = 0;
  for (const s of doc.sections) {
    if (s.details?.body?.length) folds += 1;
    for (const i of s.items ?? []) if (i.details?.body?.length) folds += 1;
    for (const o of s.options ?? []) if (o.details?.body?.length) folds += 1;
    for (const a of s.addons ?? []) if (a.details?.body?.length) folds += 1;
  }

  console.log(`Документ: ${DOC_ID}`);
  console.log(`Адреса:   /offer/${SLUG}`);
  console.log(`Секцій:   ${doc.sections.length}, катів «подробиці»: ${folds}`);
  for (const s of doc.sections) {
    const kind = s._type.replace("proposal", "").replace("Block", "").padEnd(8);
    console.log(`  · ${kind} ${s.heading || s.eyebrow || s._type}`);
  }

  if (!APPLY) {
    console.log("\nDry-run. Для запису: --apply");
    return;
  }

  // Скриншоти лежать у /public фронтенду — у Sanity їх треба покласти один раз.
  const shotsDir = join(here, "..", "..", "..", "code-site-solutions", "public", "sanity-studio");
  const [desktopId, mobileId] = await Promise.all([
    ensureAsset(join(shotsDir, "admin-desktop.png"), "admin-desktop.png"),
    ensureAsset(join(shotsDir, "admin-mobile.png"), "admin-mobile.png"),
  ]);
  const shots = doc.sections.find((s) => s._key === ADMIN_SHOTS_KEY);
  shots.images = [
    img(desktopId, "На компʼютері", "Адмінка на компʼютері: зліва розділи, у центрі список записів, справа сторінка з блоками"),
    img(mobileId, "На телефоні", "Та сама адмінка на екрані телефона"),
  ];
  console.log(`
Зображення: ${desktopId}, ${mobileId}`);

  const existing = await client.getDocument(DOC_ID).catch(() => null);
  if (existing) {
    mkdirSync(backupDir, { recursive: true });
    const file = join(backupDir, `${DOC_ID}.${Date.now()}.json`);
    writeFileSync(file, JSON.stringify(existing, null, 2), "utf8");
    console.log(`\nРезервна копія: ${file}`);
  }

  await client.createOrReplace(doc);
  console.log(`\nЗаписано. Перевірити: https://www.code-site.art/offer/${SLUG}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
