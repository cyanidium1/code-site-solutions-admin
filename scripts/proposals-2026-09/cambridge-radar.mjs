/**
 * Завантажує файл у Sanity один раз: якщо ассет із таким іменем уже там,
 * перевикористовуємо. Інакше кожен запуск скрипта плодив би копії однієї
 * картинки в бібліотеці.
 */
async function ensureAsset(absPath, filename) {
  const existing = await client.fetch(
    '*[_type == "sanity.imageAsset" && originalFilename == $f][0]._id',
    { f: filename },
  );
  if (existing) return existing;
  const asset = await client.assets.upload("image", createReadStream(absPath), { filename });
  return asset._id;
}

